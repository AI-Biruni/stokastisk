#!/usr/bin/env python3.13
"""Write requirements/kaggle-t4-core.hashes.txt: every core pin with the sha256 of ALL its published distribution files (PyPI JSON API), so that
`pip download --no-deps --require-hashes` is deterministic. Reads public package metadata only. usage: gen_pin_hashes.py"""
import json, pathlib, re, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[2]
out = ["# GENERATED by scripts/release/gen_pin_hashes.py -- exact pins with sha256 of every published file for that version (pip --require-hashes)"]
for line in (ROOT / "requirements/kaggle-t4-core.txt").read_text().splitlines():
    line = line.split("#")[0].strip()
    if not line: continue
    name, _, ver = line.partition("==")
    d = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=60))
    files = [u for u in d["urls"] if not u["filename"].endswith(".egg")]
    hashes = sorted({u["digests"]["sha256"] for u in files})
    assert hashes, name
    out.append(f"{name}=={ver} \\\n    " + " \\\n    ".join(f"--hash=sha256:{h}" for h in hashes))
(ROOT / "requirements/kaggle-t4-core.hashes.txt").write_text("\n".join(out) + "\n")
print("\n".join(out)[:600])
